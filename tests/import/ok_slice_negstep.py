# 期望输出: 与原 Python 一致
# 特性: 负步长切片赋值 → 反向逐位重建（覆盖位置从 起 递减，止 是开区间）
def main() -> None:
    # 全缺省负步长：整个列表倒序覆盖
    xs = [1, 2, 3, 4, 5]
    xs[::-1] = [9, 8, 7, 6, 5]
    print(xs)
    # 显式起止负步长：止 是开区间（不覆盖 0）
    ys = [1, 2, 3, 4, 5]
    ys[2:0:-1] = [9, 8]
    print(ys)
    # 负步长 -2
    zs = [1, 2, 3, 4, 5]
    zs[::-2] = [9, 8, 7]
    print(zs)
    # 显式起止 + 负步长 -2
    ws = [0, 1, 2, 3, 4, 5]
    ws[5:0:-2] = [9, 8, 7]
    print(ws)
    # 右值是变量
    vs = [0, 1, 2, 3, 4]
    rv = [7, 6, 5]
    vs[4:1:-1] = rv
    print(vs)


if __name__ == "__main__":
    main()
